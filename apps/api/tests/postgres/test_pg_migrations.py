from collections.abc import Iterator

import pytest
from alembic import command
from sqlalchemy import inspect, text

from app.db.engine import create_db_engine
from app.db.fts import POSTGRES_FTS_INDEX
from tests.postgres.conftest import run_alembic, throwaway_database

KEYWORD_INDEX_REVISION = "6d544dac46b3"


@pytest.fixture
def url() -> Iterator[str]:
    # Migration tests change the schema, so each gets its own database.
    with throwaway_database() as url:
        yield url


def query(url: str, sql: str, **params: object) -> list[tuple[object, ...]]:
    engine = create_db_engine(url)
    try:
        with engine.connect() as connection:
            return [tuple(row) for row in connection.execute(text(sql), params)]
    finally:
        engine.dispose()


def vector_column_type(url: str) -> str:
    rows = query(
        url,
        "SELECT udt_name FROM information_schema.columns "
        "WHERE table_name = 'chunk_embeddings' AND column_name = 'vector'",
    )
    return str(rows[0][0])


def fts_index_definition(url: str) -> str | None:
    rows = query(
        url, "SELECT indexdef FROM pg_indexes WHERE indexname = :name", name=POSTGRES_FTS_INDEX
    )
    return str(rows[0][0]) if rows else None


def has_vector_extension(url: str) -> bool:
    return bool(query(url, "SELECT 1 FROM pg_extension WHERE extname = 'vector'"))


def test_upgrade_creates_postgres_search_objects(url: str) -> None:
    run_alembic(url, command.upgrade, "head")

    assert has_vector_extension(url)
    assert vector_column_type(url) == "vector"
    definition = fts_index_definition(url)
    assert definition is not None
    assert "USING gin" in definition
    assert "to_tsvector('english'::regconfig, text)" in definition


def test_models_and_migrations_are_in_sync(url: str) -> None:
    run_alembic(url, command.upgrade, "head")

    # Raises AutogenerateDiffsDetected if models and migrations have drifted.
    run_alembic(url, command.check)


def test_downgrading_postgres_search_restores_bytea(url: str) -> None:
    run_alembic(url, command.upgrade, "head")
    run_alembic(url, command.downgrade, KEYWORD_INDEX_REVISION)

    assert vector_column_type(url) == "bytea"
    assert fts_index_definition(url) is None
    assert not has_vector_extension(url)


def test_downgrade_to_base_and_upgrade_again(url: str) -> None:
    run_alembic(url, command.upgrade, "head")
    run_alembic(url, command.downgrade, "base")

    engine = create_db_engine(url)
    try:
        assert set(inspect(engine).get_table_names()) == {"alembic_version"}
    finally:
        engine.dispose()

    run_alembic(url, command.upgrade, "head")
    assert vector_column_type(url) == "vector"
