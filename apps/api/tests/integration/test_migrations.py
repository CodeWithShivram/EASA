from tests.conftest import sqlite_url

BASELINE_REVISION = "7b339cea85fb"
DOCUMENTS_REVISION = "eb5cd7e86396"
CHUNKING_CONFIG_REVISION = "e57f12a3d5ed"
EMBEDDINGS_REVISION = "29b0c28209aa"
KEYWORD_INDEX_REVISION = "6d544dac46b3"
POSTGRES_SEARCH_REVISION = "e4353f12b34f"  # a no-op on SQLite; see tests/postgres
HEAD_REVISION = POSTGRES_SEARCH_REVISION


@pytest.fixture
def database_url(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> str:
    # env.py reads the URL from application settings, exactly as in production.
    url = sqlite_url(tmp_path / "var" / "migrations.db")
    monkeypatch.setenv("EASA_DATABASE_URL", url)
    return url


@pytest.fixture
def alembic_config() -> Config:
    return Config(str(API_ROOT / "alembic.ini"))


def _tables_and_revision(url: str) -> tuple[set[str], str | None]:
    engine = create_db_engine(url)
    try:
        with engine.connect() as connection:
            # FTS5 tables are checked separately (test_keyword_index_matches_app_module).
            tables = {
                name
                for name in inspect(connection).get_table_names()
                if not is_keyword_index_object(name)
            }
            revision = None
            if "alembic_version" in tables:
                revision = connection.execute(
                    text("SELECT version_num FROM alembic_version")
                ).scalar_one_or_none()
        return tables, revision
    finally:
        engine.dispose()


def test_history_is_linear_with_a_single_head(alembic_config: Config) -> None:
    script = ScriptDirectory.from_config(alembic_config)

    assert script.get_heads() == [HEAD_REVISION]
    assert script.get_revision(POSTGRES_SEARCH_REVISION).down_revision == KEYWORD_INDEX_REVISION
    assert script.get_revision(KEYWORD_INDEX_REVISION).down_revision == EMBEDDINGS_REVISION
    assert script.get_revision(EMBEDDINGS_REVISION).down_revision == CHUNKING_CONFIG_REVISION
    assert script.get_revision(CHUNKING_CONFIG_REVISION).down_revision == DOCUMENTS_REVISION
    assert script.get_revision(DOCUMENTS_REVISION).down_revision == BASELINE_REVISION
    assert script.get_revision(BASELINE_REVISION).down_revision is None


def test_upgrade_to_head_creates_document_tables(alembic_config: Config, database_url: str) -> None:
    command.upgrade(alembic_config, "head")

    tables, revision = _tables_and_revision(database_url)
    assert tables == {"alembic_version", "documents", "document_chunks", "chunk_embeddings"}
    assert revision == HEAD_REVISION


def test_downgrade_to_baseline_removes_document_tables(
    alembic_config: Config, database_url: str
) -> None:
    command.upgrade(alembic_config, "head")
    command.downgrade(alembic_config, BASELINE_REVISION)

    assert _tables_and_revision(database_url) == ({"alembic_version"}, BASELINE_REVISION)


def test_downgrade_to_base_and_upgrade_again(alembic_config: Config, database_url: str) -> None:
    command.upgrade(alembic_config, "head")
    command.downgrade(alembic_config, "base")
    assert _tables_and_revision(database_url)[1] is None

    command.upgrade(alembic_config, "head")
    assert _tables_and_revision(database_url)[1] == HEAD_REVISION


def test_models_and_migrations_are_in_sync(alembic_config: Config, database_url: str) -> None:
    command.upgrade(alembic_config, "head")

    # Raises AutogenerateDiffsDetected if models and migrations have drifted.
    command.check(alembic_config)


def _fts_objects(url: str) -> dict[str, str]:
    engine = create_db_engine(url)
    try:
        with engine.connect() as connection:
            rows = connection.execute(
                text(
                    "SELECT name, sql FROM sqlite_master "
                    "WHERE (type = 'trigger' OR name = 'chunk_fts') AND sql IS NOT NULL"
                )
            )
            return {name: " ".join(sql.split()) for name, sql in rows}
    finally:
        engine.dispose()


def test_keyword_index_matches_app_module(
    alembic_config: Config, database_url: str, tmp_path: Path
) -> None:
    command.upgrade(alembic_config, "head")
    migrated = _fts_objects(database_url)

    reference_url = sqlite_url(tmp_path / "reference.db")
    engine = create_db_engine(reference_url)
    try:
        Base.metadata.create_all(engine)
        with engine.begin() as connection:
            create_keyword_index(connection)
    finally:
        engine.dispose()

    assert set(migrated) == {"chunk_fts", "chunk_fts_ai", "chunk_fts_ad", "chunk_fts_au"}
    assert migrated == _fts_objects(reference_url)


def test_downgrading_the_keyword_index_removes_it(
    alembic_config: Config, database_url: str
) -> None:
    command.upgrade(alembic_config, "head")
    command.downgrade(alembic_config, EMBEDDINGS_REVISION)

    assert _fts_objects(database_url) == {}
